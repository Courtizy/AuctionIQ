"""Builds Clearinghouse's Data/*.lua from a CraftSim install (MIT licence, credit in Data/README).
Usage: python3 tools/convert_craftsim.py <CraftSim folder>
Keeps only what Clearinghouse reads: per-profession specialization nodes (Midnight) and the
Concentration cost curves."""
import sys
from pathlib import Path
from lupa import LuaRuntime

SRC = Path(sys.argv[1])
OUT = Path(__file__).resolve().parents[1] / "Data"
# Midnight child skill lines, as Clearinghouse keys professions
PROFS = {"Alchemy": 2906, "Enchanting": 2909, "Jewelcrafting": 2914, "Inscription": 2913}
HEAD = "-- Generated by tools/convert_craftsim.py from CraftSim (MIT licence, see Data/README.md). Do not edit.\n"

def lua_runtime():
    L = LuaRuntime(unpack_returned_tuples=True)
    L.execute("CraftSim = { SPECIALIZATION_DATA = { MIDNIGHT = {} } }")
    return L

def num(v):
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return repr(v)

def ser(t, L):
    if isinstance(t, bool):
        return "true" if t else "false"
    if L.eval("type")(t) != "table":
        return num(t) if isinstance(t, (int, float)) else '"%s"' % t if isinstance(t, str) else str(t).lower()
    keys = list(t.keys())
    parts = []
    seq = keys == list(range(1, len(keys) + 1))
    for k in sorted(keys, key=lambda k: (isinstance(k, str), k)):
        v = ser(t[k], L)
        if seq:
            parts.append(v)
        elif isinstance(k, str) and k.isidentifier():
            parts.append(f"{k}={v}")
        elif isinstance(k, str):
            parts.append(f'["{k}"]={v}')
        else:
            parts.append(f"[{num(k)}]={v}")
    return "{" + ",".join(parts) + "}"

for name, line in PROFS.items():
    L = lua_runtime()
    src = (SRC / "Data/SpecializationData/Midnight" / f"{name}.lua").read_text(encoding="utf-8")
    src = src.replace("local CraftSim = select(2, ...)", "")
    L.execute(src)
    d = L.eval(f"CraftSim.SPECIALIZATION_DATA.MIDNIGHT.{name.upper()}_DATA")
    body = "local _, CH = ...\nCH.SpecData = CH.SpecData or {}\n"
    body += f"CH.SpecData[{line}] = {{ name = \"{name}\",\n"
    body += " recipes = " + ser(d.recipeMapping, L) + ",\n"
    body += " nodes = " + ser(d.nodeData, L) + ",\n}\n"
    (OUT / f"Spec{name}.lua").write_text(HEAD + body)

L = lua_runtime()
src = (SRC / "Data/ConcentrationCurveData.lua").read_text(encoding="utf-8").replace("local CraftSim = select(2, ...)", "")
L.execute(src)
curves = L.eval("CraftSim.CONCENTRATION_CURVE_DATA")
lines = ["local _, CH = ...", "CH.ConcCurves = {"]
for k in sorted(curves.keys()):
    c = curves[k]
    lines.append(f"[{k}]={{c={ser(c.costConstantData, L)},v={ser(c.curveData, L)}}},")
lines.append("}")
(OUT / "ConcentrationCurves.lua").write_text(HEAD + "\n".join(lines) + "\n")
print("ok")

"""Builds Operations/Craft/Specs/Spec<Profession>.lua from Blizzard's own game tables (DB2), as wago.tools
publishes them as CSV. Re-run after a patch:

    python3 tools/build_specs.py            # downloads the tables it needs into tools/db2/
    python3 tools/build_specs.py --offline  # uses the copies already in tools/db2/

For each Midnight crafting profession it writes the specialization nodes (path nodes with their
ranks, perks with the path they hang off and the rank that unlocks them), each node's stats, and
for each recipe the nodes whose bonuses apply to it. Disenchanting skill and Tailoring's cloth drop
chance come out as "gatherskill"; perks the game describes only in words keep those words ("text"). A node applies to a recipe when the node's
profession trait and the recipe's spell share a label (ProfessionTraitXLabel / SpellLabel).
"""
import csv
import re
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB2 = Path(__file__).resolve().parent / "db2"
OUT = ROOT / "Operations" / "Craft" / "Specs"
TABLES = ["SkillLine", "SkillLineXTraitTree", "SkillLineAbility", "TraitNode", "TraitNodeXTraitNodeEntry", "TraitNodeEntry",
          "TraitDefinition", "TraitCond", "TraitNodeXTraitCond", "ProfessionTrait", "ProfessionTraitXEffect", "ProfessionEffect",
          "ProfessionEffectType", "ProfessionTraitXLabel", "SpellLabel"]
# Midnight child skill lines, as AuctionIQ keys professions
PROFS = {"Alchemy": 2906, "Blacksmithing": 2907, "Enchanting": 2909, "Engineering": 2910, "Inscription": 2913,
         "Jewelcrafting": 2914, "Leatherworking": 2915, "Tailoring": 2918}
HEAD = "-- Generated by tools/build_specs.py from Blizzard's game tables (via wago.tools). Do not edit.\n"


def fetch(offline):
    DB2.mkdir(exist_ok=True)
    for t in TABLES:
        p = DB2 / f"{t}.csv"
        if offline and p.exists():
            continue
        with urllib.request.urlopen(f"https://wago.tools/db2/{t}/csv", timeout=120) as r:
            p.write_bytes(r.read())


def load(t):
    with open(DB2 / f"{t}.csv", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def stat_key(name):
    """CraftSim-compatible stat names: 'Crafting Speed' -> 'craftingspeed'."""
    n = name.lower()
    if "trait ranks by points" in n:
        return "gatherskill"  # skill at disenchanting, or the cloth drop chance: not a recipe stat
    if "tokenization" in n:
        return "dummyeffectfor#tokenization(dnt)"
    n = n.split(" (dnt - write")[0]
    return n.replace(" ", "")


def clean(text):
    """A perk's description as plain words: the first line, without the game's text codes."""
    text = text.split("|n")[0].strip()
    text = re.sub(r"\$@spellname\d+", "it", text)
    return text.replace('"', "'") if "$" not in text else ""


def build():
    effect_type = {r["EnumID"]: stat_key(r["Name_lang"]) for r in load("ProfessionEffectType")}
    effects = {r["ID"]: r for r in load("ProfessionEffect")}
    trait_effects = defaultdict(list)
    for r in load("ProfessionTraitXEffect"):
        trait_effects[r["ProfessionTraitID"]].append(effects[r["ProfessionEffectID"]])
    trait_labels = defaultdict(set)
    for r in load("ProfessionTraitXLabel"):
        trait_labels[r["ProfessionTraitID"]].add(r["LabelID"])
    traits_of_def = defaultdict(list)
    for r in load("ProfessionTrait"):
        traits_of_def[r["TraitDefinitionID"]].append(r["ID"])
    spell_labels = defaultdict(set)
    for r in load("SpellLabel"):
        spell_labels[r["SpellID"]].add(r["LabelID"])
    defs = {r["ID"]: r for r in load("TraitDefinition")}
    entries = {r["ID"]: r for r in load("TraitNodeEntry")}
    node_entries = defaultdict(list)
    for r in load("TraitNodeXTraitNodeEntry"):
        if r["TraitNodeEntryID"] in entries:
            node_entries[r["TraitNodeID"]].append(entries[r["TraitNodeEntryID"]])
    conds = {r["ID"]: r for r in load("TraitCond")}
    node_conds = defaultdict(list)
    for r in load("TraitNodeXTraitCond"):
        if r["TraitCondID"] in conds:
            node_conds[r["TraitNodeID"]].append(conds[r["TraitCondID"]])
    trees = defaultdict(set)
    for r in load("SkillLineXTraitTree"):
        trees[r["SkillLineID"]].add(r["TraitTreeID"])
    nodes_by_tree = defaultdict(list)
    for r in load("TraitNode"):
        nodes_by_tree[r["TraitTreeID"]].append(r)
    recipes_of = defaultdict(set)
    for r in load("SkillLineAbility"):
        recipes_of[r["SkillupSkillLineID"]].add(r["Spell"])  # the expansion's skill line, not the parent

    out = {}
    for name, line in PROFS.items():
        nodes, labels_of = {}, {}
        for tree in sorted(trees[str(line)]):
            for n in nodes_by_tree[tree]:
                es = node_entries[n["ID"]]
                if not es:
                    continue
                stats, labels, icon = {}, set(), 0
                for e in es:
                    d = defs.get(e["TraitDefinitionID"]) or {}
                    icon = icon or int(d.get("OverrideIcon") or 0)
                    for t in traits_of_def[e["TraitDefinitionID"]]:
                        labels |= trait_labels[t]
                        for eff in trait_effects[t]:
                            k = effect_type.get(eff["ProfessionEffectTypeEnumID"], "effect" + eff["ProfessionEffectTypeEnumID"])
                            stats[k] = stats.get(k, 0) + float(eff["Amount"])
                base = n["Type"] == "1"
                text = ""
                if not stats:
                    # a perk with no numbers ("a chance of more Eversinging Dust") is kept for its words;
                    # a path node with none (Jewelcrafting's prospecting paths) for the tree
                    for e in es:
                        d = defs.get(e["TraitDefinitionID"]) or {}
                        text = text or clean(d.get("OverrideDescription_lang") or "")
                    if not base and not text:
                        continue
                parent, unlock = n["ID"], None
                if not base:
                    for c in node_conds[n["ID"]]:
                        if c["TraitNodeID"] != "0" and c["CondType"] == "2":
                            parent, unlock = c["TraitNodeID"], int(c["SpentAmountRequired"])
                node = {"maxRank": max(int(e["MaxRanks"]) for e in es), "nodeID": int(parent), "stats": stats}
                if base:
                    node["base"] = True
                    if icon:
                        node["icon"] = icon
                if unlock is not None:
                    node["unlock"] = unlock
                if text and not base:
                    node["text"] = text
                nodes[int(n["ID"])] = node
                if stats:
                    labels_of[int(n["ID"])] = labels
        # every recipe the skill line teaches, plus any other spell carrying one of this profession's
        # trait labels (recipes from vendors, quests and drops aren't all in SkillLineAbility). An extra
        # spell that isn't a recipe is harmless: the addon only looks recipes up by their ID.
        used = set().union(*labels_of.values()) if labels_of else set()
        spells = set(recipes_of[str(line)]) | {sp for sp, ls in spell_labels.items() if ls & used}
        recipes = {}
        for spell in spells:
            sl = spell_labels.get(spell)
            if not sl:
                continue
            hit = [nid for nid, ls in labels_of.items() if ls & sl]
            if hit:
                recipes[int(spell)] = sorted(hit)
        out[name] = (line, nodes, recipes)
    return out


def num(v):
    return str(int(v)) if float(v).is_integer() else repr(v)


def ser(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return num(v)
    if isinstance(v, str):
        return '"%s"' % v
    if isinstance(v, list):
        return "{" + ",".join(ser(x) for x in v) + "}"
    parts = []
    for k in sorted(v, key=lambda k: (isinstance(k, str), k)):
        if isinstance(k, str) and k.isidentifier():
            parts.append(f"{k}={ser(v[k])}")
        elif isinstance(k, str):
            parts.append(f'["{k}"]={ser(v[k])}')
        else:
            parts.append(f"[{k}]={ser(v[k])}")
    return "{" + ",".join(parts) + "}"


def write(data):
    for name, (line, nodes, recipes) in data.items():
        body = "local _, CH = ...\nCH.SpecData = CH.SpecData or {}\n"
        body += f'CH.SpecData[{line}] = {{ name = "{name}",\n recipes = {ser(recipes)},\n nodes = {ser(nodes)},\n}}\n'
        (OUT / f"Spec{name}.lua").write_text(HEAD + body, encoding="utf-8")
        print(f"{name}: {len(nodes)} nodes, {len(recipes)} recipes")


if __name__ == "__main__":
    fetch("--offline" in sys.argv)
    write(build())

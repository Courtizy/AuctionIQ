"""Builds the crafting data AuctionIQ can't ask the game for at run time, from Blizzard's own game
tables (DB2), as wago.tools publishes them as CSV:

    Data/ConcentrationCurves.lua                        Concentration cost at any skill
    Professions/AuctionIQ_Enchanting/EnchantScrolls.lua the scroll each quality of an enchant makes

Re-run after a patch:

    python3 tools/build_crafting_data.py            # downloads the tables it needs into tools/db2/
    python3 tools/build_crafting_data.py --offline  # uses the copies already in tools/db2/

If the download is refused, fetch each table with curl into tools/db2/<Table>.csv
(https://wago.tools/db2/<Table>/csv) and run with --offline.

How the game stores a recipe's Concentration cost:

    CraftingData        one row per craftingDataID (what GetCraftingOperationInfo reports); its
                        CraftingDifficultyID names the difficulty row
    CraftingDifficulty  ConcentrationSkillCurveID     curve over skill as a percent of difficulty
                                                      (0 to 100), giving a multiplier
                        ConcentrationDifficultyCurveID curve over the recipe's difficulty, giving
                                                      the base cost (the constant)
    CurvePoint          the points of every curve: CurveID, OrderIndex, Pos_0 (x), Pos_1 (y)

    cost = multiplier(skill / difficulty) * constant(difficulty), each read between its points

The Lua keeps the skill curve's x as a fraction (percent / 100): Stats.ConcentrationCost reads it
against skill / difficulty. Only a few distinct curve pairs exist, so each is written once and every
craftingDataID points at one.

Enchants: the game gives no output item for an enchant, but CraftingDataEnchantQuality lists, for
each craftingDataID, the scroll item at each rank.
"""
import csv
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB2 = Path(__file__).resolve().parent / "db2"
OUT = ROOT / "Data" / "ConcentrationCurves.lua"
SCROLLS = ROOT / "Professions" / "AuctionIQ_Enchanting" / "EnchantScrolls.lua"
TABLES = ["CraftingData", "CraftingDifficulty", "CurvePoint", "CraftingDataEnchantQuality"]
HEAD = "-- Generated by tools/build_crafting_data.py from Blizzard's game tables (via wago.tools). Do not edit.\n"


def fetch(offline):
    DB2.mkdir(exist_ok=True)
    for t in TABLES:
        p = DB2 / f"{t}.csv"
        if offline and p.exists():
            continue
        with urllib.request.urlopen(f"https://wago.tools/db2/{t}/csv", timeout=120) as r:
            p.write_bytes(r.read())


def load(t):
    with open(DB2 / f"{t}.csv", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(s):
    """A CSV number as Lua writes it: whole numbers without a decimal point."""
    v = float(s)
    return str(int(v)) if v == int(v) else repr(v)


def curves():
    pts = {}
    for r in load("CurvePoint"):
        pts.setdefault(int(r["CurveID"]), []).append((int(r["OrderIndex"]), float(r["Pos_0"]), float(r["Pos_1"])))
    return {cid: [(x, y) for _, x, y in sorted(p)] for cid, p in pts.items()}


def lua_points(points, scale=1.0):
    return "{" + ",".join(f"[{num(x / scale)}]={num(y)}" for x, y in points) + "}"


def build():
    cv = curves()
    diff = {}
    for r in load("CraftingDifficulty"):
        skill, base = int(r["ConcentrationSkillCurveID"] or 0), int(r["ConcentrationDifficultyCurveID"] or 0)
        if skill in cv and base in cv:
            diff[int(r["ID"])] = (skill, base)
    pairs, index, mapping = [], {}, {}
    for r in load("CraftingData"):
        d = diff.get(int(r["CraftingDifficultyID"] or 0))
        if not d:
            continue
        if d not in index:
            pairs.append(d)
            index[d] = len(pairs)
        mapping[int(r["ID"])] = index[d]
    return cv, pairs, mapping


def write(cv, pairs, mapping):
    out = [HEAD, "local _, AuctionIQ = ...\n",
           "-- Only a few distinct curves exist: each recipe's craftingDataID points at one of them, shared.\n",
           "-- c: base cost by difficulty; v: multiplier by skill as a fraction of difficulty.\n", "local C = {\n"]
    for skill, base in pairs:
        out.append(f"{{c={lua_points(cv[base])},v={lua_points(cv[skill], 100.0)}}},\n")
    out.append("}\nlocal MAP = {\n")
    ids = sorted(mapping)
    for i in range(0, len(ids), 16):
        out.append(",".join(f"[{k}]={mapping[k]}" for k in ids[i:i + 16]) + ",\n")
    out.append("}\nAuctionIQ.ConcCurves = {}\nfor id, i in pairs(MAP) do AuctionIQ.ConcCurves[id] = C[i] end\n")
    OUT.write_text("".join(out), encoding="utf-8", newline="\n")
    return len(pairs), len(mapping)


def write_scrolls():
    by = {}
    for r in load("CraftingDataEnchantQuality"):
        by.setdefault(int(r["CraftingDataID"]), []).append((int(r["Rank"]), int(r["ItemID"])))
    out = [HEAD, "-- Enchanting: each enchant's scroll item per quality, keyed by the recipe's craftingDataID\n",
           "-- (C_TradeSkillUI.GetCraftingOperationInfo). The game gives no output item for an enchant; its\n",
           "-- CraftingDataEnchantQuality table lists the scroll at each rank.\n",
           "local AuctionIQ = AuctionIQ\nAuctionIQ.EnchantScrolls = {\n"]
    n = 0
    for cid in sorted(by):
        items = [i for _, i in sorted(by[cid]) if i]
        if items:
            out.append(f"[{cid}]={{{','.join(map(str, items))}}},\n")
            n += 1
    out.append("}\n")
    SCROLLS.write_text("".join(out), encoding="utf-8", newline="\n")
    return n


if __name__ == "__main__":
    fetch("--offline" in sys.argv)
    n, m = write(*build())
    print(f"wrote {OUT.relative_to(ROOT)}: {n} curves, {m} recipes")
    print(f"wrote {SCROLLS.relative_to(ROOT)}: {write_scrolls()} enchants")
